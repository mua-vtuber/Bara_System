/** Explicit runtime allowlist applied to git-tracked paths only. */
export function isRuntimeSource(path: string): boolean {
  const p = path.replaceAll("\\", "/");
  if (p === "package.json" || p === "bun.lock" || p === "LICENSE" || SETUP_FILES.has(p)) return true;
  if (!p.startsWith("apps/memory/")) return false;
  if (p === "apps/memory/package.json") return true;
  if (/(?:^|\/)(?:data|secrets|models|node_modules|test-fixtures|__tests__|cache)(?:\/|$)/i.test(p)) return false;
  if (/(?:\.test\.|\.spec\.|test-setup|\/tests?\/|\.snap$)/i.test(p)) return false;
  if (p.startsWith("apps/memory/src/")) return /\.(?:ts|sql|yaml|yml|json|txt)$/.test(p);
  if (p.startsWith("apps/memory/web/")) return /\.(?:html|css|js|svg|png|webp|woff2?)$/.test(p);
  if (p === "apps/memory/scripts/fetch-kiwi-model.ts" || p === "apps/memory/scripts/prefetch-core-models.ts" ||
    p === "apps/memory/scripts/portable-memory.ts" || p === "apps/memory/scripts/db-snapshot.ts" ||
    p === "apps/memory/scripts/restore-backup.ts") return true;
  return false;
}

export function sha256(bytes: Uint8Array): string { return createHash("sha256").update(bytes).digest("hex"); }
export async function hashFile(path: string): Promise<string> { return sha256(await readFile(path)); }
export function run(argv: string[], cwd: string): string {
  const child = Bun.spawnSync(argv, { cwd, stdout: "pipe", stderr: "pipe" });
  if (child.exitCode !== 0) throw new Error(`${argv[0]} failed (${child.exitCode}): ${new TextDecoder().decode(child.stderr).slice(0, 600)}`);
  return new TextDecoder().decode(child.stdout);
}

/** The Core paths the runtime payload is built from. */
export const CORE_RUNTIME_FILES = ["package.json", "bun.lock", "LICENSE"];
export const CORE_RUNTIME_DIRS = ["apps/memory", "apps/setup"];
export const CORE_RUNTIME_PATHS = [...CORE_RUNTIME_FILES, ...CORE_RUNTIME_DIRS];
export const DIRTY_PATHS_SHOWN = 5;

export async function listTrackedRuntimeFiles(coreRoot: string): Promise<string[]> {
  const output = Bun.spawnSync(["git", "ls-files", "-z", "--", ...CORE_RUNTIME_PATHS],
    { cwd: coreRoot, stdout: "pipe", stderr: "pipe" });
  if (output.exitCode !== 0) throw new Error("Core source must be a Git checkout at build time");
  return new TextDecoder().decode(output.stdout).split("\0").filter(isRuntimeSource).sort();
}

/** Tracked files under `paths` that differ from HEAD (modified, staged or deleted). Untracked files are never copied
 * into a bundle; the built dashboard files are regenerated by `build:dashboard` and are excluded. */
export function dirtyPaths(coreRoot: string, paths: readonly string[]): string[] {
  return run(["git", "status", "--porcelain", "--untracked-files=no", "--", ...paths, ...GENERATED_DASHBOARD.map((path) => `:(exclude)${path}`)], coreRoot)
    .split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
}

/** Packaging copies the working tree but records `git rev-parse HEAD` as `sourceCommit`. A tracked runtime file that
 * differs from HEAD would ship code that commit does not contain, so stop and name the files. */
export function assertCleanCoreTree(coreRoot: string): void {
  const changed = dirtyPaths(coreRoot, CORE_RUNTIME_PATHS);
  if (changed.length === 0) return;
  const shown = changed.slice(0, DIRTY_PATHS_SHOWN).join(", ") + (changed.length > DIRTY_PATHS_SHOWN ? ", ..." : "");
  throw new Error(`Core checkout has ${changed.length} uncommitted change(s) in tracked runtime files: ${shown}. Commit or discard them before packaging.`);
}

/** Runtime source of an adapter: the root workspace files and the adapter's own `src` code, never tests, data or scratch. */
export function isAdapterSource(dir: string, path: string): boolean {
  const p = path.replaceAll("\\", "/");
  if (p === "package.json" || p === "bun.lock" || p === "LICENSE" || p === `${dir}/package.json`) return true;
  if (!p.startsWith(`${dir}/src/`)) return false;
  if (/(?:^|\/)(?:data|node_modules|__tests__|_tmp-[^/]*)(?:\/|$)/i.test(p)) return false;
  if (/(?:\.test\.|\.spec\.|\/tests?\/|\.snap$)/i.test(p)) return false;
  return /\.(?:ts|json)$/.test(p);
}

export interface ImportClosure { files: string[]; packages: string[] }
function packageName(spec: string): string { return spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0]!; }
function resolveSource(root: string, fromDir: string, spec: string): string | null {
  const base = resolve(fromDir, spec);
  for (const candidate of [base, base.replace(/\.js$/, ".ts"), `${base}.ts`, join(base, "index.ts")]) {
    if (!existsSync(candidate) || !statSync(candidate).isFile()) continue;
    const path = relative(root, candidate).split(sep).join("/");
    return path.startsWith("..") ? null : path;
  }
  return null;
}

/** Every repository file `entry` loads at run time (relative imports and re-exports; type-only imports are erased by
 * the transpiler) and every package name it imports. A relative import that names no file stops the bundle. */
export async function importClosure(coreRoot: string, entry: string): Promise<ImportClosure> {
  const transpiler = new Bun.Transpiler({ loader: "ts" });
  const root = resolve(coreRoot);
  const files = new Set<string>(), packages = new Set<string>();
  const queue = [entry];
  while (queue.length > 0) {
    const path = queue.pop()!;
    if (files.has(path)) continue;
    files.add(path);
    const absolute = join(root, path);
    for (const item of transpiler.scanImports(await readFile(absolute, "utf8"))) {
      if (!item.path.startsWith(".")) { packages.add(packageName(item.path)); continue; }
      const target = resolveSource(root, dirname(absolute), item.path);
      if (target === null) throw new Error(`Cannot resolve ${item.path} imported by ${path}`);
      queue.push(target);
    }
  }
  return { files: [...files].sort(), packages: [...packages].sort() };
}

async function copyInto(coreRoot: string, stageDir: string, files: readonly string[]): Promise<void> {
  for (const path of files) {
    const source = join(coreRoot, path);
    if (!existsSync(source)) throw new Error(`Missing bundle file: ${path}`);
    await mkdir(dirname(join(stageDir, path)), { recursive: true });
    await copyFile(source, join(stageDir, path));
  }
}

/** How many of the lock lines a prune newly introduced the refusal names, so the cause is visible in a CI log. */
const UNAPPROVED_LOCK_LINES_SHOWN = 5;

/** Bun's frozen install rejects workspaces absent from the bundle; prune them without resolving new versions. */
async function pruneLock(coreRoot: string, stageDir: string): Promise<void> {
  run([process.execPath, "install", "--lockfile-only"], stageDir);
  const original = new Set((await readFile(join(coreRoot, "bun.lock"), "utf8")).split(/\r?\n/));
  const introduced = (await readFile(join(stageDir, "bun.lock"), "utf8")).split(/\r?\n/).filter((line) => line && !original.has(line));
  if (introduced.length > 0)
    throw new Error(`Pruned production lock introduced an unapproved dependency/version (${introduced.length} line(s)): ` +
      introduced.slice(0, UNAPPROVED_LOCK_LINES_SHOWN).map((line) => line.trim()).join(" | "));
}

/** The memory server's bundle source (what `package-runtime.ts` always built): dashboard, tracked runtime files, pruned lock. */
export async function stageServerSource(coreRoot: string, stageDir: string): Promise<string[]> {
  run([process.execPath, "run", "build:dashboard"], join(coreRoot, "apps", "memory"));
  const tracked = await listTrackedRuntimeFiles(coreRoot);
  for (const required of ["package.json", "bun.lock", "LICENSE", "apps/memory/package.json", ...SETUP_FILES]) {
    if (!tracked.includes(required)) throw new Error(`Core runtime file is not committed: ${required}`);
  }
  const files = [...new Set([...tracked, ...GENERATED_DASHBOARD])].sort();
  await copyInto(coreRoot, stageDir, files);
  await pruneLock(coreRoot, stageDir);
  return files;
}

/** A start file's import chain may only reach the adapter's own folder and the memory sources; anything else is not
 * part of the bundle, so name that cause instead of calling the file uncommitted. */
export function assertClosureWithinRoots(name: string, files: readonly string[], roots: readonly string[]): void {
  const outside = files.filter((path) => !roots.some((root) => path.startsWith(root)));
  if (outside.length > 0) throw new Error(`Adapter ${name} imports files outside the allowed bundle roots (${roots.join(", ")}): ${outside.join(", ")}`);
}

/** An adapter's dashboard manifest, placed at its release root so the memory server finds `current/app.manifest.json`. */
export const RELEASE_MANIFEST_FILE = "app.manifest.json";
const BUILTIN = /^(?:node:|bun:|bun$)/;
/** An adapter's bundle source: its tracked runtime files plus the repository files its start file imports (S-1). */
export async function stageAdapterSource(coreRoot: string, stageDir: string, name: string): Promise<{ files: string[]; workDir: string; startFile: string }> {
  const source = adapterSource(name);
  const pkg = JSON.parse(await readFile(join(coreRoot, source.dir, "package.json"), "utf8")) as { dependencies?: Record<string, string> };
  const startFile = adapterStartFile(pkg, name);
  const listed = Bun.spawnSync(["git", "ls-files", "-z", "--", "package.json", "bun.lock", "LICENSE", source.dir, "apps/memory/src"],
    { cwd: coreRoot, stdout: "pipe", stderr: "pipe" });
  if (listed.exitCode !== 0) throw new Error("Core source must be a Git checkout at build time");
  const tracked = new Set(new TextDecoder().decode(listed.stdout).split("\0").filter(Boolean));
  const closure = await importClosure(coreRoot, `${source.dir}/${startFile}`);
  assertClosureWithinRoots(name, closure.files, [`${source.dir}/`, "apps/memory/src/"]);
  const untracked = closure.files.filter((path) => !tracked.has(path));
  if (untracked.length > 0) throw new Error(`Adapter ${name} imports files that are not committed: ${untracked.join(", ")}`);
  const foreign = closure.packages.filter((pkgName) => !BUILTIN.test(pkgName) && !(pkgName in (pkg.dependencies ?? {})));
  if (foreign.length > 0) throw new Error(`Adapter ${name} imports packages its package.json does not declare: ${foreign.join(", ")}`);
  const files = [...new Set([...[...tracked].filter((path) => isAdapterSource(source.dir, path)), ...closure.files])].sort();
  await copyInto(coreRoot, stageDir, files);
  const manifest = `${source.dir}/${RELEASE_MANIFEST_FILE}`;
  if (tracked.has(manifest)) {
    await copyFile(join(coreRoot, manifest), join(stageDir, RELEASE_MANIFEST_FILE));
    files.push(RELEASE_MANIFEST_FILE);
    files.sort();
  }
  await pruneLock(coreRoot, stageDir);
  return { files, workDir: source.dir, startFile };
}

export type BundleComponent = { kind: "server" } | { kind: "adapter"; name: string };
/** Tracked paths whose changes would make a bundle differ from its commit (`deploy:a1` refuses them, spec 5.4). */
export function bundlePaths(component: BundleComponent): string[] {
  return component.kind === "server" ? [...CORE_RUNTIME_PATHS] : [...CORE_RUNTIME_FILES, adapterSource(component.name).dir, "apps/memory/src"];
}

export interface ComponentBundle { archive: string; sourceSha: string; appVersion: string; commit: string; workDir: string; startFile: string }

export async function buildComponentBundle(coreRoot: string, outDir: string, component: BundleComponent): Promise<ComponentBundle> {
  if (process.versions.bun !== BUN_VERSION) throw new Error(`Build with Bun ${BUN_VERSION}`);
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });
  const stage = join(outDir, "stage"), archive = join(outDir, "source.tar.gz");
  const staged = component.kind === "server"
    ? { files: await stageServerSource(coreRoot, stage), workDir: "apps/memory", startFile: "src/index.ts" }
    : await stageAdapterSource(coreRoot, stage, component.name);
  await archiveSource(stage, staged.files, archive);
  const appVersion = (JSON.parse(await readFile(join(stage, staged.workDir, "package.json"), "utf8")) as { version?: unknown }).version;
  if (typeof appVersion !== "string") throw new Error(`${staged.workDir}/package.json has no version`);
  return { archive, sourceSha: await hashFile(archive), appVersion, commit: run(["git", "rev-parse", "HEAD"], coreRoot).trim(),
    workDir: staged.workDir, startFile: staged.startFile };
}

/** The pinned Linux Bun for `arch`, downloaded once into `cacheDir` and checked against its release digest. */
export async function linuxBun(arch: RemoteArch, cacheDir: string): Promise<{ path: string; sha256: string }> {
  const asset = arch === "arm64" ? ASSETS.linuxArm64 : ASSETS.linuxX64;
  await mkdir(cacheDir, { recursive: true });
  const digest = await downloadAsset(asset, cacheDir, cacheDir);
  return { path: join(cacheDir, asset.output), sha256: digest };
}

/** The tar that reads zip and Windows paths: the system bsdtar on Windows (Git Bash puts GNU tar first on PATH, which
 * can do neither), plain `tar` elsewhere. */
export function tarExecutable(): string {
  if (process.platform !== "win32") return "tar";
  const systemRoot = process.env.SystemRoot;
  if (!systemRoot) throw new Error("SystemRoot is not set; cannot locate the Windows tar.exe");
  return join(systemRoot, "System32", "tar.exe");
}

export async function downloadAsset(asset: Asset, outputRoot: string, downloadDir: string): Promise<string> {
  const zip = join(downloadDir, asset.name);
  if (!existsSync(zip) || await hashFile(zip) !== asset.sha256) {
    const response = await fetch(`${RELEASE}/${asset.name}`, { redirect: "follow" });
    if (!response.ok) throw new Error(`Bun release download failed (${response.status})`);
    const bytes = new Uint8Array(await response.arrayBuffer());
    if (sha256(bytes) !== asset.sha256) throw new Error(`Bun release digest mismatch: ${asset.name}`);
    await writeFile(zip, bytes);
  }
  const extracted = join(downloadDir, `extract-${asset.name}`);
  await rm(extracted, { recursive: true, force: true });
  await mkdir(extracted, { recursive: true });
  run([tarExecutable(), "-xf", zip, "-C", extracted], downloadDir);
  const source = join(extracted, asset.member);
  const target = join(outputRoot, asset.output);
  await mkdir(dirname(target), { recursive: true });
  await copyFile(source, target);
  return hashFile(target);
}

export async function archiveSource(coreDir: string, files: string[], output: string): Promise<void> {
  const entries: Record<string, Uint8Array> = {};
  for (const path of files) entries[path] = await readFile(join(coreDir, path));
  // Bun 1.3.6 on Windows writes plain TAR through Bun.write(Archive) even when
  // the Archive constructor requests gzip. Compress the TAR bytes explicitly.
  const temporary = `${output}.${randomUUID()}.tar`;
  try {
    await Bun.write(temporary, new Bun.Archive(entries));
    await Bun.write(output, Bun.gzipSync(await Bun.file(temporary).bytes()));
  } finally { await rm(temporary, { force: true }); }
}

